// Prerenders every route in src/App.jsx to static HTML (index.html, about/index.html, …)
// and writes sitemap.xml. Run via `npm run build:html` after `npm run build:js`.
import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

process.env.NODE_ENV = "production";

const SITE = "https://nedorezova.coach";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cacheDir = join(root, "node_modules", ".cache", "prerender");
const serverBundle = join(cacheDir, "server.cjs");

// Bundle the server entry (and its dependencies) for node as CommonJS —
// react-router-dom 6 has no "exports" map, so node ESM cannot resolve "react-router-dom/server".
await build({
  entryPoints: [join(root, "src", "server.jsx")],
  outfile: serverBundle,
  bundle: true,
  platform: "node",
  format: "cjs",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "warning",
});

const { render, routes } = await import(`${pathToFileURL(serverBundle).href}?t=${Date.now()}`);
const template = await readFile(join(root, "src", "template.html"), "utf8");

const escapeAttr = (s) =>
  s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

for (const { path, title, description } of routes) {
  const url = `${SITE}${path}`;
  const html = template
    .replaceAll("{{title}}", escapeAttr(title))
    .replaceAll("{{description}}", escapeAttr(description))
    .replaceAll("{{url}}", url)
    .replace("<!--app-->", () => render(path));

  const outFile = join(root, path.slice(1), "index.html");
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, html);
  console.log(`prerendered ${path} -> ${outFile.slice(root.length + 1)}`);
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by npm run build; edit src/ -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes.map(({ path }) => `  <url><loc>${SITE}${path}</loc></url>`).join("\n")}
</urlset>
`;
await writeFile(join(root, "sitemap.xml"), sitemap);
console.log("wrote sitemap.xml");
